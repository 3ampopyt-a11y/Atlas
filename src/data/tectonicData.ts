// Helper to ensure polygon ring winding is counter-clockwise (covering < 2*PI steradians on a sphere)
function normalizePolygonRing(ring: [number, number][]): [number, number][] {
  const closedRing = [...ring];
  if (
    closedRing[0][0] !== closedRing[closedRing.length - 1][0] ||
    closedRing[0][1] !== closedRing[closedRing.length - 1][1]
  ) {
    closedRing.push(closedRing[0]);
  }
  const testFeat = {
    type: 'Feature',
    geometry: {
      type: 'Polygon',
      coordinates: [closedRing],
    },
    properties: {},
  };
  try {
    const area = geoArea(testFeat as any);
    if (area > 2 * Math.PI) {
      return [...closedRing].reverse();
    }
  } catch {
    // fallback to original ring
  }
  return closedRing;
}

// Convert a TectonicPlate into a properly oriented GeoJSON Feature
export function getPlateGeoJsonFeature(plate: TectonicPlate): any {
  if (!plate.polygons || plate.polygons.length === 0) return null;

  const normalizedRings = plate.polygons.map((ring) => normalizePolygonRing(ring));

  if (normalizedRings.length === 1) {
    return {
      type: 'Feature',
      id: plate.id,
      properties: {
        id: plate.id,
        name: plate.name,
        shortName: plate.shortName,
        color: plate.color,
        type: plate.type,
      },
      geometry: {
        type: 'Polygon',
        coordinates: [normalizedRings[0]],
      },
    };
  }

  // MultiPolygon (for Pacific Plate and split antimeridian plates)
  return {
    type: 'Feature',
    id: plate.id,
    properties: {
      id: plate.id,
      name: plate.name,
      shortName: plate.shortName,
      color: plate.color,
      type: plate.type,
    },
    geometry: {
      type: 'MultiPolygon',
      coordinates: normalizedRings.map((ring) => [ring]),
    },
  };
}

