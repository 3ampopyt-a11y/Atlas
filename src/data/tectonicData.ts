import { geoArea } from 'd3-geo';

export interface TectonicPlate {
  id: string;
  name: string;
  shortName: string;
  type: 'Major' | 'Minor';
  lithosphereType: 'Oceanic' | 'Continental' | 'Mixed';
  areaMkm2: number;
  percentageEarthSurface: number;
  driftDirection: string;
  driftSpeedMmYr: number;
  driftVector: { dx: number; dy: number; arrow: string };
  centerCoordinates: [number, number]; // [lng, lat]
  color: string;
  description: string;
  majorFeatures: string[];
  adjacentPlates: string[];
  majorEarthquakes: string[];
  activeVolcanoes: string[];
  polygons: [number, number][][]; // Array of coordinate rings (each ring is [lng, lat][])
}

export interface FaultLine {
  id: string;
  name: string;
  type: 'Convergent' | 'Divergent' | 'Transform' | 'Complex';
  color: string;
  isRingOfFire?: boolean;
  coordinates: [number, number][]; // Array of [lng, lat]
  description: string;
  speed?: string;
  notableFeatures: string;
}

export interface SeismicHotspot {
  id: string;
  name: string;
  type: 'Volcano' | 'Subduction Trench' | 'Rift Zone' | 'Hotspot' | 'Historic Megaquake';
  coordinates: [number, number];
  intensity: 'Extreme' | 'High' | 'Moderate';
  plateId: string;
  details: string;
  elevationOrDepth?: string;
  notableEvent?: string;
}

