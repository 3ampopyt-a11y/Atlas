// Retrieve plate for a country
export function getPlateForCountryCode(countryCode?: string): TectonicPlate | undefined {
  if (!countryCode) return undefined;
  const plateId = COUNTRY_TO_PLATE_ID[countryCode.toUpperCase()];
  if (!plateId) return undefined;
  return TECTONIC_PLATES.find((p) => p.id === plateId);
}

