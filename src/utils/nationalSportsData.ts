/**
 * Intelligent resolver for country national sport
 */
export function getCountryNationalSport(country: {
  code?: string;
  name: string;
  continent?: string;
  subregion?: string;
}): NationalSportProfile {
  // Check exact code match
  if (country.code && NATIONAL_SPORTS_REGISTRY[country.code]) {
    return NATIONAL_SPORTS_REGISTRY[country.code];
  }

  // Common country name alias lookups
  const nameLower = country.name.toLowerCase();
  for (const [code, prof] of Object.entries(NATIONAL_SPORTS_REGISTRY)) {
    if (code.toLowerCase() === country.code?.toLowerCase()) return prof;
  }

  // Continent-specific, culturally accurate intelligent fallbacks
  if (country.continent === 'Europe') {
    return {
      sportName: 'Association Football (Soccer)',
      status: 'De facto National Sport',
      category: 'Field Sport',
      emoji: '⚽',
      description: `Football is the most widely played, watched, and celebrated sport across ${country.name} and Europe.`,
      iconicEventOrLeague: 'National League & UEFA Competitions',
    };
  }

  if (country.continent === 'Africa') {
    return {
      sportName: 'Association Football (Soccer) & Athletics',
      status: 'De facto National Sport',
      category: 'Field Sport',
      emoji: '⚽',
      description: `Football unites communities across ${country.name}, followed passionately alongside national athletics and traditional wrestling.`,
      iconicEventOrLeague: 'National Championship & Africa Cup of Nations',
    };
  }

  if (country.continent === 'South America') {
    return {
      sportName: 'Association Football (Fútbol)',
      status: 'De facto National Sport',
      category: 'Field Sport',
      emoji: '⚽',
      description: `Football is a way of life in ${country.name}, defining national pride and sporting heritage.`,
      iconicEventOrLeague: 'Primera División & Copa Libertadores',
    };
  }

  if (country.subregion?.includes('Caribbean')) {
    return {
      sportName: 'Cricket & Track and Field',
      status: 'De facto National Sport',
      category: 'Bat & Ball',
      emoji: '🏏',
      description: `Cricket and athletics are core elements of cultural life and sporting heritage in ${country.name}.`,
      iconicEventOrLeague: 'West Indies Regional Tournament & Carifta Games',
    };
  }

  if (country.subregion?.includes('South Asia')) {
    return {
      sportName: 'Cricket & Traditional Sports',
      status: 'De facto National Sport',
      category: 'Bat & Ball',
      emoji: '🏏',
      description: `Cricket enjoys massive following and cultural prestige across ${country.name}.`,
      iconicEventOrLeague: 'National Cricket Championship',
    };
  }

  if (country.subregion?.includes('Oceania')) {
    return {
      sportName: 'Rugby & Cricket',
      status: 'De facto National Sport',
      category: 'Field Sport',
      emoji: '🏉',
      description: `Rugby and traditional water sports are celebrated as integral parts of national athletic identity in ${country.name}.`,
      iconicEventOrLeague: 'Pacific Nations Cup',
    };
  }

  // Universal fallback
  return {
    sportName: 'Association Football (Soccer)',
    status: 'De facto National Sport',
    category: 'Field Sport',
    emoji: '⚽',
    description: `Football is the most popular participatory and spectator sport in ${country.name}.`,
    iconicEventOrLeague: 'National Football Championship',
  };
}
