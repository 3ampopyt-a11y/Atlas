/**
 * National sport from the curated registry; null where no source names one
 */
export function getCountryNationalSport(country: {
  id?: string;
  code?: string;
  name: string;
  continent?: string;
  subregion?: string;
  demographics?: { population: number };
}): NationalSportProfile | null {
  // Nobody lives there permanently, so there is no national sport to name
  if (country.demographics && !country.demographics.population) return null;

  // Entries that borrow another country's ISO code are keyed by their own id
  const key = SHARED_ISO_ENTRIES.has(country.id || '') ? country.id : country.code;
  // No sourced national sport: show none rather than a regional guess
  return (key && NATIONAL_SPORTS_REGISTRY[key]) || null;
}
